export function buildIndustries(): Industry[] {
  const out: Industry[] = [];
  for (const [sector, rows] of Object.entries(SECTORS)) {
    for (const r of rows) {
      const [name, startupCost, baseMargin, volatility, cyclicality, capitalIntensity, laborIntensity, techIntensity, regulationSensitivity, skillId, tags] = r;
      out.push({
        id: `${sector.toLowerCase()}_${name.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
        name,
        sector,
        description: `${name} — ${sector} sector business.`,
        startupCost,
        baseMargin,
        volatility,
        cyclicality,
        capitalIntensity,
        laborIntensity,
        techIntensity,
        regulationSensitivity,
        skillId,
        tags,
      });
    }
  }
  return out;
}

